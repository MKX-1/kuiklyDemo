package com.example.aistock.theme

/**
 * 动效 token —— 把「感觉」变成可复用的数值。
 *
 * 为什么动效也要做成 token：动画时长如果随手写（这里 200ms、那里 700ms），
 * 界面会显得散；统一档位之后，整屏的节奏是一致的 —— 这是「编排好的入场序列」
 * 比「零散微交互」更好看的根本原因。
 *
 * 档位来自行业通行区间（也与设计方法论给出的基准一致）：
 *   微交互 150–200ms / 常规 300–400ms / 场景 600–800ms。
 */
object AppMotion {

    /** 一次性微反馈：按下、选中、颜色切换。快到「无感」但又不生硬。 */
    const val FAST_MS = 160

    /** 常规过渡：卡片展开、面板浮现。默认就用这一档。 */
    const val BASE_MS = 320

    /** 场景级：页面入场、底部弹层升降。 */
    const val SLOW_MS = 640

    /** 入场单项时长。 */
    const val APPEAR_MS = 300

    /**
     * 相邻条目入场的时间差（错峰步长）。
     *
     * 40ms 是个偏密的取值：列表条目多（7–10 条）时，60–120ms 会让最后一条等太久，
     * 用户会感觉「卡」。列表用 40–60ms，少量分区块用 80–120ms。
     */
    const val STAGGER_STEP_MS = 45

    /**
     * 错峰总上限：第 4 项之后的延迟不再线性增长。
     *
     * 没有这个封顶，第 20 条要等 20×45=900ms 才出现 —— 用户早滚过去了。
     */
    const val STAGGER_MAX_MS = 320

    /** 呼吸/脉冲类循环动效的单程时长（一个来回 = 2×）。 */
    const val PULSE_MS = 900
}
